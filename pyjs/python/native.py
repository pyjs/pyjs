def round_result(call):
    from pyjs.analysis.analyzer import BUILTINS, analyzed_value_type
    from pyjs.analysis.diagnostics import DiagnosticCode
    from pyjs.analysis.objects import UnionType
    from pyjs.analysis.type_relations import get_type_members
    from pyjs.analysis.value_representation import analyzed_numeric_format
    from pyjs.native.enum_ops import storage_name

    result = call.standard(defer_representation_arguments=(0, 1))
    number = result.args[0] if result.args else next(
        keyword.value for keyword in result.keywords if keyword.arg == "number"
    )
    if any(member.container.scope.is_builtins and storage_name(member) not in {"int", "bool", "float", "object"}
           for member in get_type_members(analyzed_value_type(number))):
        call.visitor.fail(number, DiagnosticCode.INCOMPATIBLE_ARGUMENT,
                          "Argument 'number' to round expects a number or __round__ protocol, got "
                          + analyzed_value_type(number).to_annotation_str())
    if any(storage_name(member) not in {"int", "bool", "float"}
           for member in get_type_members(analyzed_value_type(number))):
        from pyjs.native.rounding import application_round
        return application_round(call, result)
    digits = result.args[1] if len(result.args) > 1 else next(
        (keyword.value for keyword in result.keywords if keyword.arg == "ndigits"), None)
    if digits is not None and any(storage_name(member) not in {"int", "bool", "NoneType"}
                                  for member in get_type_members(analyzed_value_type(digits))):
        call.visitor.fail(digits, DiagnosticCode.INCOMPATIBLE_ARGUMENT,
                          "Argument 'ndigits' to round expects int|NoneType, got "
                          + analyzed_value_type(digits).to_annotation_str())
    if analyzed_value_type(result) is BUILTINS.search("object"):
        # The application fallback must not erase the original numeric fallback
        # result when a valid scalar union matches no single overload.
        result = call.with_result_type(UnionType(types=[BUILTINS.search("int"), BUILTINS.search("float")]).type)
    # No ndigits converts a float to an ordinary int. Integer results and
    # float results with ndigits retain the receiver's numeric format.
    if analyzed_value_type(result) is analyzed_value_type(number):
        call.set_result_formats(result, analyzed_numeric_format(number))
    return result


configure_js(_round, analysis=round_result)


