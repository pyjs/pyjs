"""Python semantics available to the experimental native backend.

This intentionally starts smaller than the JavaScript surface. Adding a
definition is a promise that native emission implements the corresponding
Python behavior, so unsupported operations fail during shared analysis.

Sequence overloads put slices before the broad index-protocol object fallback;
their distinct result and replacement types must survive signature selection.
"""

