def include_definition(name, value, module) -> bool:
    """Defer ordinary definitions until reachable code needs their shape."""
    return is_declaration(value, "native") or isinstance(value, (bool, float, int, str, list, tuple, dict, set, frozenset))


def should_analyze_body(func) -> bool:
    """Analyze Python implementations but trust native runtime declarations."""
    return not (
        is_declaration(func.py_func, "native")
        or func.cls is not None
        and is_declaration(func.cls.py_obj, "native")
    )


