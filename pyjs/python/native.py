def splitlines_arguments(call):
    import ast

    result = call.standard(defer_representation_arguments=tuple(range(len(call.node.args))))
    # Convert the flag through ordinary truth analysis, retaining subclass
    # callbacks before tree shaking. There is just one named flag; standard
    # binding rejects duplicates and unknown names. Unbound builtin methods
    # remain unsupported during lowering (a single receiver can bind as this
    # flag). Rewriting the flag positionally preserves evaluation order.
    values = [*result.args, *(keyword.value for keyword in result.keywords)]
    result.args = [ast.copy_location(call.visitor.truth_test(value, value), value) for value in values]
    result.keywords = []
    return result


configure_js(_str.splitlines, analysis=splitlines_arguments)
configure_js(_bytes.splitlines, analysis=splitlines_arguments)


