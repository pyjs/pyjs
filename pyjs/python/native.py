def reversed_result(call):
    import ast
    import inspect

    from pyjs.analysis.analyzer import (
        _CallAnalysis,
        analyzed_value_type,
        declared_protocol_method,
    )
    from pyjs.analysis.diagnostics import DiagnosticCode
    from pyjs.analysis.objects import AnalyzedExpression, Function
    from pyjs.analysis.type_relations import get_type_members

    if len(call.node.args) != 1 or call.node.keywords or isinstance(call.node.args[0], ast.Starred):
        return call.standard()
    value = call.visitor.visit(call.node.args[0])
    members = get_type_members(analyzed_value_type(value))
    if all(member.container.scope.is_builtins for member in members):
        expression = ast.copy_location(ast.Call(
            func=call.node.func, args=[AnalyzedExpression(value)], keywords=[]), call.node)
        return _CallAnalysis(call.visitor, expression, call.function).preserving_iterator("reversed()", 0)
    if any(member.container.scope.is_builtins for member in members):
        call.visitor.fail(call.node, DiagnosticCode.UNSUPPORTED_SYNTAX,
                          "native reversed does not support mixed builtin and application receivers")
    for member in members:
        base = member.super
        while base is not None and not base.container.scope.is_builtins:
            base = base.super
        if base is not None and base.generic_name in {"list", "tuple", "str", "bytes", "dict", "set", "frozenset"}:
            call.visitor.fail(call.node, DiagnosticCode.UNSUPPORTED_SYNTAX,
                              "native reversed does not support builtin-container subclasses")
        declaration = inspect.getattr_static(member.py_obj, "__reversed__", None)
        method = declared_protocol_method(member, "__reversed__", declaration)
        if not isinstance(method, Function) or method.is_property or method.is_classmethod:
            call.visitor.fail(call.node, DiagnosticCode.UNSUPPORTED_SYNTAX,
                              "native reversed requires an instance or static __reversed__ method")
    # Special-method lookup bypasses instance fields. Use an ordinary call so
    # virtual dispatch, arbitrary return types, roots and errors share one path.
    # Reuse the analyzed receiver on both paths: re-visiting source recursively
    # would multiply analysis work at every level of nested reversed() calls.
    method = ast.Attribute(value=AnalyzedExpression(value), attr="__reversed__", ctx=ast.Load())
    method.class_lookup = True
    expression = ast.fix_missing_locations(ast.copy_location(
        ast.Call(func=method, args=[], keywords=[]), call.node))
    return call.visitor.visit_contextual_expression(
        expression, call.visitor.contextual_types.get(call.node),
        call.visitor.contextual_numeric_formats.get(call.node),
        call.visitor.contextual_representations.get(call.node),
    )


configure_js(_reversed, analysis=reversed_result)


