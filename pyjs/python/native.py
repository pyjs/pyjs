def power_result(call):
    import ast

    from pyjs.analysis.diagnostics import DiagnosticCode

    if any(isinstance(arg, ast.Starred) for arg in call.node.args) or any(kw.arg is None for kw in call.node.keywords):
        call.visitor.fail(call.node, DiagnosticCode.UNSUPPORTED_SYNTAX,
                          "pow() argument unpacking is not supported",
                          help="Pass two or three explicit positional arguments.")
    literal_none = (len(call.node.args) == 3 and isinstance(call.node.args[2], ast.Constant)
                    and call.node.args[2].value is None)
    if call.node.keywords or len(call.node.args) != 2 and not literal_none:
        result = call.standard()
        if len(call.node.args) != 3:
            return result
        from pyjs.analysis.analyzer import BUILTINS, analyzed_value_type
        from pyjs.analysis.objects import UnionType
        from pyjs.analysis.representation import direct_representation
        from pyjs.analysis.value_representation import (
            operation_numeric_format,
            possible_numeric_formats,
        )

        formats = possible_numeric_formats(result.args)
        if len(formats) > 1:
            call.visitor.fail_mixed_numeric_formats(call.node)
        numeric = operation_numeric_format(result.args[:2])
        if formats and any(isinstance(analyzed_value_type(arg), UnionType) for arg in result.args):
            call.visitor.fail(call.node, DiagnosticCode.INCOMPATIBLE_ARGUMENT,
                              "fixed-width modular pow() requires narrowed operands")
        # Only an exact ordinary int base gives a portable exponent reflected
        # subclass priority. bool and IntEnum inherit int's slot but are not
        # bases of the exponent's portable class, so their ordinary slot wins.
        # A represented modulus alone does not own the result.
        if (analyzed_value_type(result.args[0]) is not BUILTINS.search("int")
                and not possible_numeric_formats(result.args[:1])):
            numeric = None
        return call.set_result_representation(result, direct_representation(numeric, None))
    # Binary pow (also an explicit literal None modulus) uses the operator
    # protocol, including reflected subclass priority and result representation.
    # Do not erase operands to object through the broad declaration before
    # ordinary expression analysis.
    expression = ast.copy_location(ast.BinOp(left=call.node.args[0], op=ast.Pow(), right=call.node.args[1]), call.node)
    return call.visitor.visit_contextual_expression(
        expression, call.visitor.contextual_types.get(call.node),
        call.visitor.contextual_numeric_formats.get(call.node),
        call.visitor.contextual_representations.get(call.node),
    )


configure_js(_pow, analysis=power_result)


