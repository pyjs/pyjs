"""Android's streaming JSON writer; closing it closes the underlying writer."""

from pyjs import jvm
from pyjs.java.io import Writer


@jvm.native("android/util/JsonWriter")
class JsonWriter:
    def __init__(self, writer: Writer) -> None: ...

    @jvm.native("android/util/JsonWriter", name="beginObject", invocation="virtual")
    def begin_object(self) -> JsonWriter: ...

    @jvm.native("android/util/JsonWriter", name="endObject", invocation="virtual")
    def end_object(self) -> JsonWriter: ...

    @jvm.native("android/util/JsonWriter", name="beginArray", invocation="virtual")
    def begin_array(self) -> JsonWriter: ...

    @jvm.native("android/util/JsonWriter", name="endArray", invocation="virtual")
    def end_array(self) -> JsonWriter: ...

    def name(self, name: str) -> JsonWriter: ...

    @jvm.native("android/util/JsonWriter", name="value", invocation="virtual")
    def string(self, value: str | None) -> JsonWriter: ...

    @jvm.native("android/util/JsonWriter", name="value", invocation="virtual")
    def integer(self, value: int) -> JsonWriter: ...

    @jvm.native("android/util/JsonWriter", name="value", invocation="virtual")
    def boolean(self, value: bool) -> JsonWriter: ...

    @jvm.native("android/util/JsonWriter", name="nullValue", invocation="virtual")
    def null(self) -> JsonWriter: ...

    def flush(self) -> None: ...
    def close(self) -> None: ...
