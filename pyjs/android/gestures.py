"""Android's native pinch-scale recognizer."""
from pyjs import jvm
from pyjs.android import Context
from pyjs.android.motion import MotionEvent
from pyjs.java import f32


@jvm.native("android/view/ScaleGestureDetector$OnScaleGestureListener", interface=True)
class OnScaleGestureListener:
    def onScale(self, detector: ScaleGestureDetector) -> bool: ...
    def onScaleBegin(self, detector: ScaleGestureDetector) -> bool: ...
    def onScaleEnd(self, detector: ScaleGestureDetector) -> None: ...


@jvm.native("android/view/ScaleGestureDetector")
class ScaleGestureDetector:
    def __init__(self, context: Context, listener: OnScaleGestureListener) -> None: ...
    def onTouchEvent(self, event: MotionEvent) -> bool: ...
    def isInProgress(self) -> bool: ...
    def getScaleFactor(self) -> f32: ...
    def getFocusX(self) -> f32: ...
    def getFocusY(self) -> f32: ...
