@jvm.native("android/graphics/Paint$Style")
class PaintStyle:
    FILL: ClassVar[Annotated[PaintStyle, jvm.field(writable=False)]] = None
    STROKE: ClassVar[Annotated[PaintStyle, jvm.field(writable=False)]] = None


@jvm.native("android/graphics/Paint")
class Paint:
    ANTI_ALIAS_FLAG: ClassVar[Annotated[i32, jvm.field(writable=False)]] = 1

    def __init__(self, flags: i32) -> None: ...
    def setColor(self, color: i32) -> None: ...
    def setTextSize(self, size: f32) -> None: ...
    def setStrokeWidth(self, width: f32) -> None: ...
    def setStyle(self, style: PaintStyle) -> None: ...
    def measureText(self, text: str) -> f32: ...


@jvm.native("android/graphics/Canvas")
class Canvas:
    def save(self) -> i32: ...
    def restoreToCount(self, count: i32) -> None: ...
    def translate(self, x: f32, y: f32) -> None: ...
    def scale(self, x: f32, y: f32) -> None: ...
    def drawColor(self, color: i32) -> None: ...
    def drawLine(self, x1: f32, y1: f32, x2: f32, y2: f32, paint: Paint) -> None: ...
    def drawRoundRect(self, left: f32, top: f32, right: f32, bottom: f32,
                      rx: f32, ry: f32, paint: Paint) -> None: ...
    def drawText(self, text: str, x: f32, y: f32, paint: Paint) -> None: ...
