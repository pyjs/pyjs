"""Android SQLite primitives; callers own transactions, cursors and statements.

These are native, blocking APIs. Use a worker for application I/O and keep a
transaction on one thread. Closing a database must not race its active users.
Cursor rows are bounded by Android's CursorWindow; simpleQueryForString reads
large scalar text without that per-row window limit.
"""

from pyjs import jvm
from pyjs.java import JVMArray, i32


@jvm.native("android/database/SQLException")
class SQLException(Exception):
    def getMessage(self) -> str | None: ...


@jvm.native("android/database/sqlite/SQLiteException")
class SQLiteException(SQLException):
    pass


@jvm.native("android/database/sqlite/SQLiteConstraintException")
class SQLiteConstraintException(SQLiteException):
    pass


@jvm.native("android/database/sqlite/SQLiteDoneException")
class SQLiteDoneException(SQLiteException):
    pass


@jvm.native("android/database/Cursor", interface=True)
class Cursor:
    def moveToNext(self) -> bool: ...
    def getString(self, column: i32) -> str | None: ...
    def getLong(self, column: i32) -> int: ...
    def isNull(self, column: i32) -> bool: ...
    def close(self) -> None: ...


@jvm.native("android/database/sqlite/SQLiteDatabase$CursorFactory", interface=True)
class CursorFactory:
    pass


@jvm.native("android/database/sqlite/SQLiteStatement")
class SQLiteStatement:
    def bindString(self, index: i32, value: str) -> None: ...
    def bindLong(self, index: i32, value: int) -> None: ...
    def bindNull(self, index: i32) -> None: ...
    def clearBindings(self) -> None: ...
    def execute(self) -> None: ...
    def executeInsert(self) -> int: ...
    def executeUpdateDelete(self) -> i32: ...
    def simpleQueryForString(self) -> str | None: ...
    def close(self) -> None: ...


@jvm.native("android/database/sqlite/SQLiteDatabase")
class SQLiteDatabase:
    def execSQL(self, sql: str) -> None: ...
    def compileStatement(self, sql: str) -> SQLiteStatement: ...
    def rawQuery(self, sql: str, arguments: JVMArray[str] | None) -> Cursor: ...
    def beginTransaction(self) -> None: ...
    def setTransactionSuccessful(self) -> None: ...
    def endTransaction(self) -> None: ...
    def inTransaction(self) -> bool: ...
    def getVersion(self) -> i32: ...
    def setVersion(self, version: i32) -> None: ...
    def close(self) -> None: ...


