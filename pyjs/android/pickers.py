"""Native date/time selection; Android picker months are zero-based."""

from pyjs import jvm
from pyjs.android import Context, ViewGroup
from pyjs.android.dialogs import AlertDialog
from pyjs.java import i32


@jvm.native("android/widget/DatePicker")
class DatePicker(ViewGroup):
    def getYear(self) -> i32: ...
    def getMonth(self) -> i32: ...
    def getDayOfMonth(self) -> i32: ...
    def updateDate(self, year: i32, month: i32, day: i32) -> None: ...
    def setMinDate(self, milliseconds: int) -> None: ...
    def setMaxDate(self, milliseconds: int) -> None: ...


@jvm.native("android/widget/TimePicker")
class TimePicker(ViewGroup):
    def getHour(self) -> i32: ...
    def getMinute(self) -> i32: ...
    def setHour(self, hour: i32) -> None: ...
    def setMinute(self, minute: i32) -> None: ...


@jvm.native("android/app/DatePickerDialog$OnDateSetListener", interface=True)
class DateSetListener:
    def onDateSet(self, view: DatePicker, year: i32, month: i32, day: i32) -> None: ...


@jvm.native("android/app/TimePickerDialog$OnTimeSetListener", interface=True)
class TimeSetListener:
    def onTimeSet(self, view: TimePicker, hour: i32, minute: i32) -> None: ...


@jvm.native("android/app/DatePickerDialog")
class DatePickerDialog(AlertDialog):
    def __init__(self, context: Context, listener: DateSetListener | None,
                 year: i32, month: i32, day: i32) -> None: ...
    def getDatePicker(self) -> DatePicker: ...
    def updateDate(self, year: i32, month: i32, day: i32) -> None: ...


@jvm.native("android/app/TimePickerDialog")
class TimePickerDialog(AlertDialog):
    def __init__(self, context: Context, listener: TimeSetListener | None,
                 hour: i32, minute: i32, is_24_hour: bool) -> None: ...
    def updateTime(self, hour: i32, minute: i32) -> None: ...


@jvm.native("android/text/format/DateFormat", name="is24HourFormat")
def is_24_hour_format(context: Context) -> bool: ...
