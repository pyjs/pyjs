"""Native Java file APIs for JVM and Android applications."""

from pyjs import int8, jvm, uint16
from pyjs.java import JVMArray, i32
from pyjs.java.charset import CharsetDecoder


@jvm.native("java/io/InputStream")
class InputStream:
    def read(self, buffer: JVMArray[int8]) -> i32: ...
    def close(self) -> None: ...


@jvm.native("java/io/IOException")
class IOException(Exception):
    def getMessage(self) -> str | None: ...


@jvm.native("java/io/ByteArrayInputStream")
class ByteArrayInputStream(InputStream):
    def __init__(self, data: JVMArray[int8]) -> None: ...


@jvm.native("java/io/Reader")
class Reader:
    """Read UTF-16 code units into a bounded caller-owned character array."""

    def read(self, buffer: JVMArray[uint16], offset: i32, length: i32) -> i32: ...
    def close(self) -> None: ...


@jvm.native("java/io/InputStreamReader")
class InputStreamReader(Reader):
    def __init__(self, stream: InputStream, decoder: CharsetDecoder) -> None: ...


@jvm.native("java/io/StringReader")
class StringReader(Reader):
    def __init__(self, text: str) -> None: ...


@jvm.native("java/io/OutputStream")
class OutputStream:
    def write(self, buffer: JVMArray[int8], offset: i32, length: i32) -> None: ...
    def close(self) -> None: ...


@jvm.native("java/io/ByteArrayOutputStream")
class ByteArrayOutputStream(OutputStream):
    def __init__(self) -> None: ...
    def toString(self, charset: str) -> str: ...
    def toByteArray(self) -> JVMArray[int8]: ...


@jvm.native("java/io/Writer")
class Writer:
    def write(self, text: str) -> None: ...
    def flush(self) -> None: ...
    def close(self) -> None: ...


@jvm.native("java/io/OutputStreamWriter")
class OutputStreamWriter(Writer):
    def __init__(self, stream: OutputStream, charset: str) -> None: ...


@jvm.native("java/io/StringWriter")
class StringWriter(Writer):
    def __init__(self) -> None: ...
    def toString(self) -> str: ...


@jvm.native("java/io/File")
class File:
    def __init__(self, path: str) -> None: ...
    def getPath(self) -> str: ...
    def getName(self) -> str: ...
    def getParentFile(self) -> File | None: ...
    def exists(self) -> bool: ...
    def mkdirs(self) -> bool: ...
    def listFiles(self) -> JVMArray[File] | None: ...
    def lastModified(self) -> int: ...
    def length(self) -> int: ...
    def delete(self) -> bool: ...
    def renameTo(self, destination: File) -> bool: ...


@jvm.native("java/io/FileOutputStream")
class FileOutputStream(OutputStream):
    def __init__(self, file: File) -> None: ...


@jvm.native("java/io/FileInputStream")
class FileInputStream(InputStream):
    def __init__(self, file: File) -> None: ...


@jvm.native("java/io/File", name="createTempFile")
def create_temp_file(prefix: str, suffix: str, directory: File) -> File: ...


@jvm.native("java/io/FileDescriptor")
class FileDescriptor:
    def sync(self) -> None: ...


@jvm.native("java/io/RandomAccessFile")
class RandomAccessFile:
    def __init__(self, path: str, mode: str) -> None: ...
    def readLine(self) -> str | None: ...
    def writeBytes(self, text: str) -> None: ...
    def getFD(self) -> FileDescriptor: ...
    def close(self) -> None: ...
