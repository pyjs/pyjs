"""Native Java file APIs for JVM and Android applications."""

from pyjs import jvm


@jvm.native("java/io/IOException")
class IOException(Exception):
    def getMessage(self) -> str | None: ...


@jvm.native("java/io/OutputStream")
class OutputStream:
    def close(self) -> None: ...


@jvm.native("java/io/Writer")
class Writer:
    def write(self, text: str) -> None: ...
    def flush(self) -> None: ...
    def close(self) -> None: ...


@jvm.native("java/io/OutputStreamWriter")
class OutputStreamWriter(Writer):
    def __init__(self, stream: OutputStream, charset: str) -> None: ...


@jvm.native("java/io/StringWriter")
class StringWriter(Writer):
    def __init__(self) -> None: ...
    def toString(self) -> str: ...


@jvm.native("java/io/File")
class File:
    def __init__(self, path: str) -> None: ...
    def getPath(self) -> str: ...
    def getParentFile(self) -> File | None: ...
    def exists(self) -> bool: ...
    def length(self) -> int: ...
    def delete(self) -> bool: ...
    def renameTo(self, destination: File) -> bool: ...


@jvm.native("java/io/File", name="createTempFile")
def create_temp_file(prefix: str, suffix: str, directory: File) -> File: ...


@jvm.native("java/io/FileDescriptor")
class FileDescriptor:
    def sync(self) -> None: ...


@jvm.native("java/io/RandomAccessFile")
class RandomAccessFile:
    def __init__(self, path: str, mode: str) -> None: ...
    def readLine(self) -> str | None: ...
    def writeBytes(self, text: str) -> None: ...
    def getFD(self) -> FileDescriptor: ...
    def close(self) -> None: ...
