"""Java networking declarations available on the JVM and Android."""

from pyjs import jvm
from pyjs.java import i32
from pyjs.java.collections import JavaList, JavaMap
from pyjs.java.io import InputStream, IOException, OutputStream


@jvm.native("java/net/SocketTimeoutException")
class SocketTimeoutException(IOException):
    pass


@jvm.native("java/net/URISyntaxException")
class URISyntaxException(Exception):
    pass


@jvm.native("java/net/URLConnection")
class URLConnection:
    def setConnectTimeout(self, milliseconds: i32) -> None: ...
    def setReadTimeout(self, milliseconds: i32) -> None: ...
    def setDoOutput(self, enabled: bool) -> None: ...
    def setUseCaches(self, enabled: bool) -> None: ...
    def setRequestProperty(self, name: str, value: str) -> None: ...
    def getRequestProperties(self) -> JavaMap: ...
    def getHeaderFields(self) -> JavaMap: ...
    def getOutputStream(self) -> OutputStream: ...
    def getInputStream(self) -> InputStream: ...


@jvm.native("java/net/HttpURLConnection")
class HttpURLConnection(URLConnection):
    def setRequestMethod(self, method: str) -> None: ...
    def setInstanceFollowRedirects(self, enabled: bool) -> None: ...
    def getResponseCode(self) -> i32: ...
    def getErrorStream(self) -> InputStream | None: ...
    def disconnect(self) -> None: ...


@jvm.native("java/net/URL")
class URL:
    def __init__(self, value: str) -> None: ...
    def getProtocol(self) -> str: ...
    def getHost(self) -> str: ...
    def getPort(self) -> i32: ...
    def getPath(self) -> str: ...
    def getQuery(self) -> str | None: ...
    def getRef(self) -> str | None: ...
    def getUserInfo(self) -> str | None: ...
    def openConnection(self) -> URLConnection: ...
    def toURI(self) -> URI: ...


@jvm.native("java/net/URI")
class URI:
    def __init__(self, value: str) -> None: ...
    def parseServerAuthority(self) -> URI: ...


@jvm.native("java/net/HttpCookie")
class HttpCookie:
    def getName(self) -> str: ...
    def getValue(self) -> str: ...
    def getPath(self) -> str | None: ...
    def getSecure(self) -> bool: ...
    def hasExpired(self) -> bool: ...


@jvm.native("java/net/CookieStore", interface=True)
class CookieStore:
    def get(self, uri: URI) -> JavaList: ...
    def removeAll(self) -> bool: ...


@jvm.native("java/net/CookieHandler")
class CookieHandler:
    pass


@jvm.native("java/net/CookieHandler", name="getDefault")
def default_cookie_handler() -> CookieHandler | None: ...


@jvm.native("java/net/CookieManager")
class CookieManager(CookieHandler):
    def __init__(self) -> None: ...
    def get(self, uri: URI, request_headers: JavaMap) -> JavaMap: ...
    def put(self, uri: URI, response_headers: JavaMap) -> None: ...
    def getCookieStore(self) -> CookieStore: ...


@jvm.native("java/net/URLEncoder", name="encode")
def encode_form_value(value: str, charset: str) -> str: ...
