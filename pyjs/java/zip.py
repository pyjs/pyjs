"""Native streaming ZIP entries; callers own paths, limits and stream lifetime."""

from pyjs import jvm
from pyjs.java.io import InputStream, IOException, OutputStream


@jvm.native("java/util/zip/ZipException")
class ZipException(IOException):
    pass


@jvm.native("java/util/zip/ZipEntry")
class ZipEntry:
    def __init__(self, name: str) -> None: ...
    def getName(self) -> str: ...
    def isDirectory(self) -> bool: ...


@jvm.native("java/util/zip/ZipOutputStream")
class ZipOutputStream(OutputStream):
    def __init__(self, stream: OutputStream) -> None: ...
    def putNextEntry(self, entry: ZipEntry) -> None: ...
    def closeEntry(self) -> None: ...
    def finish(self) -> None: ...


@jvm.native("java/util/zip/ZipInputStream")
class ZipInputStream(InputStream):
    def __init__(self, stream: InputStream) -> None: ...
    def getNextEntry(self) -> ZipEntry | None: ...
    def closeEntry(self) -> None: ...
