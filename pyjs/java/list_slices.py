"""Shallow list slices retaining the receiver's specialized item storage."""

from .boxed import unbox_scalar
from .classfile import Bytecode, Method
from .diagnostics import JVMUnsupported


def call(emitter, node, value_type):
    if node.keywords or len(node.args) != 3:
        raise JVMUnsupported("JVM list slices require start, stop and step", node)
    for index, argument in enumerate(node.args):
        actual = emitter.expression(argument)
        default = 1 if index == 2 else 0
        nullable = actual in {"Ljava/lang/Long;", "Ljava/lang/Boolean;"}
        if nullable:
            present = emitter.new_label("slice.present")
            done = emitter.new_label("slice.argument")
            emitter.code.emit(0x59)
            emitter.code.branch(0xC7, present)
            emitter.code.emit(0x57)
            emitter.long_constant(default)
            if index != 2:
                emitter.code.emit(0x03)
            emitter.code.branch(0xA7, done)
            emitter.code.mark(present)
            actual = unbox_scalar(emitter.code, emitter.class_file, actual)
        if actual == "N":
            emitter.code.emit(0x57)
            emitter.long_constant(default)
        elif actual == "Z":
            emitter.code.emit(0x85)
        elif actual != "J":
            raise JVMUnsupported("JVM list slice bounds must be integers or None", node)
        if index != 2:
            emitter.code.emit(0x03 if actual == "N" else 0x04)
        if nullable:
            emitter.code.mark(done)
    owner = emitter.list_class(value_type)
    descriptor = f"L{owner.name};"
    if not any(method.name == "slice" for method in owner.methods):
        owner.add_method(slice_method(emitter, owner, emitter.list_item_type(value_type)))
    reference = emitter.class_file.method_reference(owner.name, "slice", f"(JZJZJ){descriptor}")
    emitter.code.emit(0xB6, reference.to_bytes(2, "big"))
    return descriptor


def slice_method(emitter, owner, item_type):
    code = Bytecode()
    length = owner.field_reference(owner.name, "length", "I")
    data = owner.field_reference(owner.name, "data", f"[{item_type}")
    code.local(0x16, 7)
    code.emit(0x09)
    code.emit(0x94)
    code.branch(0x9A, "nonzero")
    emitter.throw_python("ValueError", "slice step cannot be zero", code, owner)
    code.mark("nonzero")
    code.local(0x19, 0)
    code.emit(0xB4, length.to_bytes(2, "big"))
    code.emit(0x85)
    code.local(0x37, 9)
    code.local(0x16, 7)
    code.emit(0x09)
    code.emit(0x94)
    code.branch(0x9B, "negative")
    code.emit(0x09)
    code.local(0x37, 11)
    code.local(0x16, 9)
    code.local(0x37, 13)
    # A stride beyond the list length visits at most one item. Clamp it
    # before addition so signed-64-bit extremes cannot wrap the cursor.
    code.local(0x16, 7)
    code.local(0x16, 9)
    code.emit(0x0A)
    code.emit(0x61)
    minimum = owner.method_reference("java/lang/Math", "min", "(JJ)J")
    code.emit(0xB8, minimum.to_bytes(2, "big"))
    code.local(0x37, 7)
    code.branch(0xA7, "bounds")
    code.mark("negative")
    code.emit(0x0A)
    code.emit(0x75)
    code.local(0x37, 11)
    code.local(0x16, 9)
    code.emit(0x0A)
    code.emit(0x65)
    code.local(0x37, 13)
    code.local(0x16, 7)
    code.local(0x16, 9)
    code.emit(0x0A)
    code.emit(0x61)
    code.emit(0x75)
    maximum = owner.method_reference("java/lang/Math", "max", "(JJ)J")
    code.emit(0xB8, maximum.to_bytes(2, "big"))
    code.local(0x37, 7)
    code.mark("bounds")
    for slot, present in ((1, 3), (4, 6)):
        code.local(0x15, present)
        code.branch(0x9A, f"explicit{slot}")
        code.local(0x16, 7)
        code.emit(0x09)
        code.emit(0x94)
        code.branch(0x9B, f"reverse{slot}")
        code.local(0x16, 11 if slot == 1 else 13)
        code.branch(0xA7, f"store{slot}")
        code.mark(f"reverse{slot}")
        code.local(0x16, 13 if slot == 1 else 11)
        code.branch(0xA7, f"store{slot}")
        code.mark(f"explicit{slot}")
        code.local(0x16, slot)
        code.emit(0x09)
        code.emit(0x94)
        code.branch(0x9C, f"clamp{slot}")
        code.local(0x16, slot)
        code.local(0x16, 9)
        code.emit(0x61)
        code.local(0x37, slot)
        code.mark(f"clamp{slot}")
        code.local(0x16, slot)
        code.local(0x16, 11)
        code.emit(0xB8, maximum.to_bytes(2, "big"))
        code.local(0x16, 13)
        code.emit(0xB8, minimum.to_bytes(2, "big"))
        code.mark(f"store{slot}")
        code.local(0x37, slot)
    code.emit(0xBB, owner.constants.class_(owner.name).to_bytes(2, "big"))
    code.emit(0x59)
    constructor = owner.method_reference(owner.name, "<init>", "()V")
    code.emit(0xB7, constructor.to_bytes(2, "big"))
    code.local(0x3A, 15)
    code.mark("loop")
    code.local(0x16, 7)
    code.emit(0x09)
    code.emit(0x94)
    code.branch(0x9B, "reverse_test")
    code.local(0x16, 1)
    code.local(0x16, 4)
    code.emit(0x94)
    code.branch(0x9C, "done")
    code.branch(0xA7, "append")
    code.mark("reverse_test")
    code.local(0x16, 1)
    code.local(0x16, 4)
    code.emit(0x94)
    code.branch(0x9E, "done")
    code.mark("append")
    code.local(0x19, 15)
    code.local(0x19, 0)
    code.emit(0xB4, data.to_bytes(2, "big"))
    code.local(0x16, 1)
    code.emit(0x88)
    code.emit(emitter.array_load_opcode(item_type))
    append = owner.method_reference(owner.name, "append", f"({item_type})V")
    code.emit(0xB6, append.to_bytes(2, "big"))
    code.local(0x16, 1)
    code.local(0x16, 7)
    code.emit(0x61)
    code.local(0x37, 1)
    code.branch(0xA7, "loop")
    code.mark("done")
    code.local(0x19, 15)
    code.emit(0xB0)
    return Method(0x0001, "slice", f"(JZJZJ)L{owner.name};", code.render(), 6, 16)
